#!/usr/bin/env python3
"""Conservative structural comparison for two rg-dis Motorola 68000 listings.

The executable arguments are GEMDOS PRGs. Listings must be generated by rg-dis
with --annotate-offsets; data directives are excluded from instruction counts.
Branch destinations are ignored for initial sequence alignment, then checked
through the resulting address map so changed control flow stays visible.
"""
from __future__ import annotations

import argparse
from collections import Counter
import difflib
import hashlib
import json
import re
from pathlib import Path

OFFSET = re.compile(r";\s*\$([0-9A-Fa-f]{4,8})\s*\|")
LABEL = re.compile(r"^([A-Za-z_.$][\w.$]*):\s*$")
INSN = re.compile(r"^\s{4}([A-Z][A-Z0-9]*(?:\.[BWL])?)\s*(.*?)\s*$")
BRANCH = re.compile(r"^(?:B(?:RA|SR|CC|CS|EQ|GE|GT|HI|LE|LS|LT|MI|NE|PL|VC|VS)|DB(?:CC|CS|EQ|F|GE|GT|HI|LE|LS|LT|MI|NE|PL|RA|T|VC|VS)|JMP|JSR)\b", re.I)
TARGET = re.compile(r"(?:_L[0-9A-Fa-f]+|[A-Za-z_.$][\w.$]*)")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def parse_listing(text: str, code_ranges: list[tuple[int, int]] | None = None) -> list[dict]:
    """Extract address-tagged decoded instructions and labels from rg-dis asm."""
    result = []
    labels: dict[str, int] = {}
    for line in text.splitlines():
        lm = LABEL.match(line)
        om = OFFSET.search(line)
        if lm and om:
            labels[lm.group(1)] = int(om.group(1), 16)
            continue
        if not om:
            continue
        code = line.split(";", 1)[0]
        m = INSN.match(code)
        if not m:
            continue
        mnemonic, operands = m.groups()
        if mnemonic.lower().startswith(("dc.", "ds.", "section")):
            continue
        offset = int(om.group(1), 16)
        if code_ranges is not None and not any(start <= offset < end for start, end in code_ranges):
            continue
        result.append({"offset": offset, "mnemonic": mnemonic.upper(),
                       "operands": re.sub(r"\s+", "", operands).upper()})
    for ins in result:
        ins["branch"] = bool(BRANCH.match(ins["mnemonic"]))
    return result


def token(ins: dict) -> str:
    """Exact instruction/operand token except branch destination address."""
    operands = ins["operands"]
    if ins["branch"]:
        # Branch target changes are validated after alignment; retain all other
        # operands (notably DBcc's counter register).
        targets = list(TARGET.finditer(operands))
        if targets:
            t = targets[-1]
            operands = operands[:t.start()] + "<TARGET>" + operands[t.end():]
    return ins["mnemonic"] + " " + operands


def align_instructions(left: list[dict], right: list[dict]) -> tuple[list[tuple[int, int]], list[tuple[int, int]]]:
    a = [token(i) for i in left]
    b = [token(i) for i in right]
    # The default popularity heuristic bounds work on long compiler listings;
    # common one-instruction idioms are poor unique anchors anyway.
    sm = difflib.SequenceMatcher(a=a, b=b, autojunk=True)
    matches = [(i + x, j + x) for i, j, n in sm.get_matching_blocks() for x in range(n)]
    blocks = [(i1, j1, i2 - i1) for tag, i1, i2, j1, j2 in sm.get_opcodes()
              if tag == "equal" and i2 > i1]
    return matches, blocks


def byte_stats(a: bytes, b: bytes) -> dict:
    common = min(len(a), len(b))
    same = sum(x == y for x, y in zip(a, b))
    matcher = difflib.SequenceMatcher(a=a, b=b, autojunk=True)
    blocks = matcher.get_matching_blocks()
    return {"left_bytes": len(a), "right_bytes": len(b), "same_offset_bytes": same,
            "same_offset_percent_of_smaller": round(100 * same / max(1, common), 3),
            "aligned_exact_bytes": sum(n for _, _, n in blocks),
            "longest_exact_run": max((n for _, _, n in blocks), default=0),
            "exact_alignment_blocks": sum(1 for _, _, n in blocks if n)}


def pair_branches(left: list[dict], right: list[dict], pairs: list[tuple[int, int]]) -> dict:
    lmap = {left[i]["offset"]: right[j]["offset"] for i, j in pairs}
    rmap = {right[j]["offset"]: left[i]["offset"] for i, j in pairs}
    checks = []
    for i, j in pairs:
        li, rj = left[i], right[j]
        if not li["branch"]:
            continue
        # Local rg-dis labels encode section-relative addresses. Numeric PC
        # displacements are retained verbatim and cannot be safely retargeted.
        lt = re.findall(r"_L([0-9A-F]{4,8})", li["operands"])
        rt = re.findall(r"_L([0-9A-F]{4,8})", rj["operands"])
        if lt and rt:
            lo, ro = int(lt[-1], 16), int(rt[-1], 16)
            mapped = lmap.get(lo)
            equal = mapped == ro
            checks.append({"left": li["offset"], "right": rj["offset"],
                           "left_target": lo, "right_target": ro,
                           "target_pair_mapped": mapped is not None,
                           "control_flow_matches": equal if mapped is not None else None})
        elif li["operands"] != rj["operands"]:
            checks.append({"left": li["offset"], "right": rj["offset"],
                           "left_target": li["operands"], "right_target": rj["operands"],
                           "target_pair_mapped": False, "control_flow_matches": False})
    known = [x for x in checks if x["control_flow_matches"] is not None]
    return {"checks": checks, "known": len(known),
            "matching": sum(x["control_flow_matches"] is True for x in known),
            "changed_or_unmapped": sum(x["control_flow_matches"] is False for x in known),
            "unresolved": len(checks) - len(known)}


def normalize_address_refs(operands: str) -> str:
    return re.sub(r"_L[0-9A-F]+", "<ADDR>", operands)


def function_pairs(left_functions: Path | None, right_functions: Path | None,
                   left: list[dict], right: list[dict], pairs: list[tuple[int, int]]) -> dict | None:
    if left_functions is None or right_functions is None:
        return None
    lf = json.loads(left_functions.read_text(encoding="utf-8"))["summaries"][0]["functions"]
    rf = json.loads(right_functions.read_text(encoding="utf-8"))["summaries"][0]["functions"]
    lf = [{"start": f["address"] - 0x10000, "end": f["address"] - 0x10000 + f["size"],
           "name": f["name"]} for f in lf]
    rf = [{"start": f["address"] - 0x10000, "end": f["address"] - 0x10000 + f["size"],
           "name": f["name"]} for f in rf]
    to_right: dict[int, Counter] = {}
    left_counts = Counter()
    right_counts = Counter()
    lidx = {ins["offset"]: i for i, ins in enumerate(left)}
    ridx = {ins["offset"]: j for j, ins in enumerate(right)}
    li_func = {}
    ri_func = {}
    for i, ins in enumerate(left):
        for fi, f in enumerate(lf):
            if f["start"] <= ins["offset"] < f["end"]:
                li_func[i] = fi; left_counts[fi] += 1; break
    for j, ins in enumerate(right):
        for fi, f in enumerate(rf):
            if f["start"] <= ins["offset"] < f["end"]:
                ri_func[j] = fi; right_counts[fi] += 1; break
    for i, j in pairs:
        if i in li_func and j in ri_func:
            to_right.setdefault(li_func[i], Counter())[ri_func[j]] += 1
    result = []
    for lfi, counts in to_right.items():
        rfi, n = counts.most_common(1)[0]
        recall = n / max(1, left_counts[lfi])
        right_precision = n / max(1, right_counts[rfi])
        confidence = "high" if n >= 10 and recall >= .8 and right_precision >= .8 else (
            "medium" if n >= 4 and recall >= .5 and right_precision >= .5 else "low")
        result.append({"left": lf[lfi], "right": rf[rfi], "matched_instruction_pairs": n,
                       "left_candidate_instructions": left_counts[lfi],
                       "right_candidate_instructions": right_counts[rfi],
                       "left_recall": round(recall, 4), "right_precision": round(right_precision, 4),
                       "confidence": confidence})
    return {"left_function_count": len(lf), "right_function_count": len(rf),
            "candidate_pairs": sorted(result, key=lambda x: x["matched_instruction_pairs"], reverse=True),
            "high_confidence_pairs": sum(x["confidence"] == "high" for x in result),
            "medium_confidence_pairs": sum(x["confidence"] == "medium" for x in result)}


def prg_sections(path: Path) -> tuple[bytes, dict]:
    raw = path.read_bytes()
    if len(raw) < 28 or raw[:2] != b"\x60\x1a":
        raise ValueError(f"{path}: expected GEMDOS PRG")
    text_size, data_size, bss_size, sym_size = (int.from_bytes(raw[i:i+4], "big") for i in (2, 6, 10, 14))
    start, end = 28, 28 + text_size + data_size
    if end > len(raw):
        raise ValueError(f"{path}: truncated sections")
    return raw[start:end], {"text_size": text_size, "data_size": data_size,
                            "bss_size": bss_size, "sym_size": sym_size,
                            "file_size": len(raw), "relocation_table_bytes": len(raw) - end}


def regions_from_json(path: Path | None) -> list[tuple[int, int]] | None:
    if path is None:
        return None
    obj = json.loads(path.read_text(encoding="utf-8"))
    summary = obj["summaries"][0]
    # `named.veto` is rg-dis's deliberate heuristic override for named code
    # candidates. The project protocol warns that these may be false positives;
    # exclude them from the primary instruction denominator and report their
    # byte coverage separately as ambiguous.
    return [(int(r["start"]) - 0x10000, int(r["end"]) - 0x10000)
            for r in summary.get("regions", [])
            if r.get("kind") == "code" and r.get("rule") != "named.veto"]


def compare(left_prg: Path, right_prg: Path, left_asm: Path, right_asm: Path,
            left_regions: Path | None = None, right_regions: Path | None = None,
            left_functions: Path | None = None, right_functions: Path | None = None) -> dict:
    lsec, llayout = prg_sections(left_prg)
    rsec, rlayout = prg_sections(right_prg)
    ltext, rtext = lsec[:llayout["text_size"]], rsec[:rlayout["text_size"]]
    li = parse_listing(left_asm.read_text(encoding="utf-8"), regions_from_json(left_regions))
    ri = parse_listing(right_asm.read_text(encoding="utf-8"), regions_from_json(right_regions))
    pairs, blocks = align_instructions(li, ri)
    identical = sum(1 for i, j in pairs if li[i]["mnemonic"] == ri[j]["mnemonic"] and li[i]["operands"] == ri[j]["operands"])
    reference_only = sum(1 for i, j in pairs if li[i]["operands"] != ri[j]["operands"]
                         and normalize_address_refs(li[i]["operands"]) == normalize_address_refs(ri[j]["operands"]))
    branch = pair_branches(li, ri, pairs)
    return {"schema": 1, "inputs": {
                "left": {"path": str(left_prg), "sha256": sha256(left_prg), **llayout},
                "right": {"path": str(right_prg), "sha256": sha256(right_prg), **rlayout}},
            "strict_bytes": {"full_prg": byte_stats(left_prg.read_bytes(), right_prg.read_bytes()),
                             "text_at_same_offsets": byte_stats(ltext, rtext)},
            "instructions": {"left_count": len(li), "right_count": len(ri),
                             "normalized_pairs": len(pairs),
                             "exact_operand_pairs": identical,
                             "changed_operand_pairs": len(pairs) - identical,
                             "address_reference_only_changes": reference_only,
                             "other_operand_changes": len(pairs) - identical - reference_only,
                             "pair_coverage_left_percent": round(100*len(pairs)/max(1,len(li)),3),
                             "pair_coverage_right_percent": round(100*len(pairs)/max(1,len(ri)),3),
                             "contiguous_match_blocks": len(blocks),
                             "longest_match_block_instructions": max((n for _,_,n in blocks),default=0),
                             "blocks": [{"left_index":i,"right_index":j,"instructions":n,
                                         "left_start":li[i]["offset"],"right_start":ri[j]["offset"],
                                         "left_end":li[i+n-1]["offset"],"right_end":ri[j+n-1]["offset"]}
                                        for i,j,n in blocks]},
            "control_flow": branch,
            "functions": function_pairs(left_functions, right_functions, li, ri, pairs),
            "unpaired": {"left": [x["offset"] for i,x in enumerate(li) if all(i != p[0] for p in pairs)],
                         "right": [x["offset"] for j,x in enumerate(ri) if all(j != p[1] for p in pairs)]}}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("left_prg", type=Path); p.add_argument("right_prg", type=Path)
    p.add_argument("left_asm", type=Path); p.add_argument("right_asm", type=Path)
    p.add_argument("--left-regions", type=Path, help="rg-dis --inspect regions JSON for left input")
    p.add_argument("--right-regions", type=Path, help="rg-dis --inspect regions JSON for right input")
    p.add_argument("--left-functions", type=Path, help="rg-dis --inspect functions JSON for left input")
    p.add_argument("--right-functions", type=Path, help="rg-dis --inspect functions JSON for right input")
    p.add_argument("--json", type=Path, help="write full machine-readable report")
    args = p.parse_args(argv)
    report = compare(args.left_prg, args.right_prg, args.left_asm, args.right_asm,
                     args.left_regions, args.right_regions, args.left_functions, args.right_functions)
    output = json.dumps(report, indent=2) + "\n"
    if args.json: args.json.write_text(output, encoding="utf-8")
    print(output, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
